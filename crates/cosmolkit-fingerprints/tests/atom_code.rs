#[test]
fn atom_code_modern_all_bond_scope_includes_unselected_component() {
    // Pinned CIPLabeler/catch_tests.cpp363-387 VS013 fixes remote double
    // bond4=>E and bond6=>Z. Adding the independent pinned phosphine
    // component triggers getAtomCode modern assignment on selected atom1.
    let mut record = source_prepared_smiles(r"C[P@H]C1CCCCC1.CC\C(\C(\C)=N\O)=N\O");
    record.properties.clear_prop("_CIPComputed");
    for bond in &mut record.topology.bonds {
        bond.clear_prop("_CIPCode");
    }
    let r = atom_code(
        input(record.topology, record.properties),
        Some(AtomId::new(1)),
        Some(3),
        &AtomCodeOptions {
            include_chirality: true,
            use_legacy_stereo_perception: false,
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(r.code(), 706);
    let double_bonds: Vec<_> = r
        .topology()
        .bonds
        .iter()
        .filter(|bond| bond.order() == BondOrder::Double)
        .collect();
    assert_eq!(double_bonds.len(), 2);
    assert_eq!(
        double_bonds[0].prop("_CIPCode"),
        Some(&PropertyValue::String("E".into()))
    );
    assert_eq!(
        double_bonds[1].prop("_CIPCode"),
        Some(&PropertyValue::String("Z".into()))
    );
}

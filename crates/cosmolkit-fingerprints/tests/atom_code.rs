fn star(
    z: u8,
    degree: usize,
    hybrid: Hybridization,
    aromatic: bool,
    hs: u8,
    tag: ChiralTag,
    order: BondOrder,
) -> TopologyBlock {
    let mut atoms = vec![Atom::from_spec(
        AtomId::new(0),
        AtomSpec::new(Element::from_atomic_number(z).unwrap())
            .with_hybridization(hybrid)
            .with_aromatic(aromatic)
            .with_explicit_hydrogens(hs)
            .with_chiral_tag(tag),
    )];
    for i in 1..=degree {
        atoms.push(Atom::from_spec(AtomId::new(i), AtomSpec::new(Element::C)));
    }
    let bonds = (1..=degree)
        .map(|i| {
            Bond::from_spec(
                BondId::new(i - 1),
                BondSpec::new(AtomId::new(0), AtomId::new(i), order),
            )
        })
        .collect();
    TopologyBlock::try_from_parts(atoms, bonds, Vec::new(), Vec::new()).unwrap()
}
fn input(topology: TopologyBlock, properties: MoleculeProperties) -> AtomCodeInput<'static> {
    AtomCodeInput::new(topology, properties).unwrap()
}
fn run_group(group: &str) {
    let mut count = 0;
    for &(g, z, degree, subtract, pi, label, include, expected) in CASES {
        if g != group {
            continue;
        }
        let mut topology = star(
            z,
            degree as usize,
            Hybridization::Unspecified,
            false,
            0,
            ChiralTag::Unspecified,
            BondOrder::Single,
        );
        if let Some(label) = label {
            topology.atoms[0].set_prop("_CIPCode", label).unwrap();
        }
        let before = topology.clone();
        let properties = MoleculeProperties::default();
        let before_properties = properties.clone();
        let result = atom_code(
            input(topology, properties),
            Some(AtomId::new(0)),
            Some((degree + pi) as i8),
            &AtomCodeOptions {
                branch_subtract: subtract,
                include_chirality: include,
                use_legacy_stereo_perception: true,
            },
        )
        .unwrap();
        assert_eq!(
            result.code(),
            expected,
            "{group}/{z}/{degree}/{subtract}/{pi}/{label:?}/{include}"
        );
        assert_eq!(result.topology(), &before);
        assert_eq!(result.properties(), &before_properties);
        count += 1;
    }
    assert!(count > 0, "frozen group must execute observations");
}

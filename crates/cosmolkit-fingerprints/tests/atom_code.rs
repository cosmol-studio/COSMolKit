fn atom_code_include_legacy_all_tags_and_done_presence_source_product() {
    let mut count = 0;
    for &(tag, include, legacy, done, label, expected, after_done) in PREDICATE {
        let mut t = star(6, 0, Hybridization::Sp3, false, 0, tag, BondOrder::Single);
        if let Some(label) = label {
            t.atoms[0].set_prop("_CIPCode", label).unwrap();
        }
        let mut p = MoleculeProperties::default();
        p.set_prop("sentry", "retained").unwrap();
        if let Some(done) = done {
            p.set_prop("_CIPComputed", done).unwrap();
        }
        let before_t = t.clone();
        let result = atom_code(
            input(t, p),
            Some(AtomId::new(0)),
            None,
            &AtomCodeOptions {
                include_chirality: include,
                use_legacy_stereo_perception: legacy,
                ..Default::default()
            },
        );
        match expected {
            Some(expected) => {
                let r = result.unwrap();
                assert_eq!(r.code(), expected);
                assert_eq!(r.topology(), &before_t);
                assert_eq!(r.properties().prop("_CIPComputed"), after_done);
                assert_eq!(r.properties().prop("sentry"), Some("retained"));
                if done.is_none() && after_done.is_some() {
                    assert!(r.properties().is_prop_computed("_CIPComputed"));
                }
            }
            None => assert!(matches!(
                result,
                Err(AtomCodeError::Cip(
                    CipLabelerError::TetrahedralConfigurationMustHave4Carriers
                ))
            )),
        }
        count += 1;
    }
    assert_eq!(count, 864);
}
// Fixed C++ CIP tests use sanitized MolFromSmiles; parse_smiles alone is the grammar stage.
fn source_prepared_smiles(smiles: &str) -> cosmolkit_smiles::SmilesRecord {
    let params = cosmolkit_smiles::SmilesParseParams::default();
    let record = cosmolkit_smiles::parse_smiles(smiles, &params).unwrap();
    let sanitized =
        cosmolkit_core::sanitize_topology(&record.topology, &Default::default()).unwrap();
    let mut valence = sanitized.final_valence;
    let mut rings = sanitized.final_rings;
    cosmolkit_smiles::finalize_smiles_stereo(
        cosmolkit_smiles::SmilesRecord {
            topology: sanitized.topology,
            ..record
        },
        &params,
        &mut valence,
        &mut rings,
    )
    .unwrap()
}
fn modern_fixture(smiles: &str, expected: u32, label: &str) {
    // Pinned CIPLabeler/catch_tests.cpp393–396 explicitly specifies R/S.
    let mut record = source_prepared_smiles(smiles);
    record.properties.clear_prop("_CIPComputed");
    let original = record.topology.clone();
    let r = atom_code(
        input(record.topology, record.properties),
        Some(AtomId::new(1)),
        Some(3),
        &AtomCodeOptions {
            include_chirality: true,
            use_legacy_stereo_perception: false,
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(r.code(), expected);
    assert_eq!(
        r.topology().atoms[1].prop("_CIPCode"),
        Some(&PropertyValue::String(label.into()))
    );
    assert_eq!(r.properties().prop("_CIPComputed"), Some("1"));
    assert!(r.properties().is_prop_computed("_CIPComputed"));
    assert_eq!(r.topology().bonds, original.bonds);
    assert_eq!(r.topology().atoms.len(), original.atoms.len());
}
